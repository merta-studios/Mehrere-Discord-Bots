function langFromDiscord(locale) {
  return DISCORD_LOCALE_MAP[locale] || 'en';
}

/** Gültiger Sprachcode? Sonst Fallback auf 'en'. */
function normalizeLang(code) {
  return LANGS[code] ? code : 'en';
}

